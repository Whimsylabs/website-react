    <p>
      Watch a school practical from the back of the room and count the minutes. Settling the class. Handing out equipment. The safety briefing. The demonstration. The method on the board, read aloud, then read again for the three students who missed it. By the time thirty teenagers actually touch anything, a good chunk of the lesson is gone, and what remains is usually enough to follow the method once, get a number, and pack away.
    </p>

