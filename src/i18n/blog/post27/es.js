    <ul>
      <li><strong>¿Qué tan profundamente está integrada la IA con la tarea de aprendizaje?</strong> Un chatbot añadido a contenido estático es muy diferente de una IA que observa el trabajo del estudiante en tiempo real. Pide detalles sobre qué datos usa la IA y cómo.</li>
      <li><strong>¿Qué pueden controlar los docentes?</strong> ¿Pueden los docentes establecer parámetros, anular decisiones de la IA, ver el razonamiento detrás de las recomendaciones? Los productos que excluyen a los docentes deberían generar preocupación.</li>
      <li><strong>¿Qué evidencia respalda las afirmaciones?</strong> Pide investigación revisada por pares, no solo testimonios. Si la empresa cita investigación, verifica si es sobre su producto específico o solo sobre tutoría con IA en general.</li>
      <li><strong>¿Cuáles son las limitaciones reconocidas?</strong> Cualquier proveedor que afirme que su IA no tiene limitaciones es ingenuo o deshonesto. Los buenos productos vienen con documentación honesta de cuándo funcionan menos bien.</li>
      <li><strong>¿Cómo complementa la enseñanza humana?</strong> Los mejores tutores de IA están diseñados para apoyar a los docentes, no reemplazarlos. Desconfía de los discursos que minimizan el rol del docente.</li>
    </ul>

